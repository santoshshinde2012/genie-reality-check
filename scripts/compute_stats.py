#!/usr/bin/env python3
"""Compute all statistics for both charts from the data files and write docs/STATS.md.

Run:  python scripts/compute_stats.py
No third-party dependencies (standard library only).
"""
import csv
import os
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")
DOCS = os.path.join(ROOT, "docs")


def read_csv(name):
    with open(os.path.join(DATA, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def sentiment_stats():
    rows = read_csv("sentiment_coding.csv")
    strength = defaultdict(int)
    concern = defaultdict(int)
    themes = []
    for r in rows:
        t, p = r["theme"], r["polarity"]
        if t not in themes:
            themes.append(t)
        if p == "strength":
            strength[t] += 1
        elif p == "concern":
            concern[t] += 1
    table = []
    for t in themes:
        s, c = strength[t], concern[t]
        total = s + c
        net = s - c
        share = (s / total * 100) if total else 0.0
        table.append((t, s, c, total, net, share))
    table.sort(key=lambda x: x[4], reverse=True)  # by net desc
    return table


def perception_stats():
    rows = read_csv("perception_vs_reality.csv")
    out = []
    for r in rows:
        credit, impact = int(r["credit"]), int(r["impact"])
        out.append((r["factor"], credit, impact, impact - credit))
    out.sort(key=lambda x: x[2], reverse=True)  # by impact desc
    return out


def pearson(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    vx = sum((x - mx) ** 2 for x in xs) ** 0.5
    vy = sum((y - my) ** 2 for y in ys) ** 0.5
    return cov / (vx * vy)


def main():
    sent = sentiment_stats()
    perc = perception_stats()

    s_total = sum(r[1] for r in sent)
    c_total = sum(r[2] for r in sent)
    m_total = s_total + c_total
    nets = [r[4] for r in sent]
    pos = sum(1 for n in nets if n > 0)
    neg = sum(1 for n in nets if n < 0)

    credits = [r[1] for r in perc]
    impacts = [r[2] for r in perc]
    r_corr = pearson(credits, impacts)

    lines = []
    lines.append("# STATS (generated by scripts/compute_stats.py)\n")
    lines.append("_Do not edit by hand; regenerate from the data files._\n")

    lines.append("## Part A — Perception vs. Reality\n")
    lines.append("| Factor | Credit | Impact | Gap (Impact-Credit) |")
    lines.append("|---|---:|---:|---:|")
    for f, cr, im, g in perc:
        lines.append(f"| {f} | {cr} | {im} | {g:+d} |")
    lines.append("")
    lines.append(f"- Mean Credit: **{sum(credits)/len(credits):.1f}**  ")
    lines.append(f"- Mean Impact: **{sum(impacts)/len(impacts):.1f}**  ")
    lines.append(f"- Mean Gap: **{sum(im-cr for _,cr,im,_ in perc)/len(perc):+.1f}**  ")
    lines.append(f"- Over-credited (Gap<0): **{sum(1 for *_,g in perc if g<0)}**; "
                 f"Under-credited (Gap>0): **{sum(1 for *_,g in perc if g>0)}**  ")
    lines.append(f"- Credit-vs-Impact correlation (by design): **r = {r_corr:.2f}**\n")

    lines.append("## Part B — Practitioner sentiment\n")
    lines.append("| Theme | Strength | Concern | Total | Net | Strength share |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for t, s, c, tot, net, share in sent:
        lines.append(f"| {t} | {s} | {c} | {tot} | {net:+d} | {share:.1f}% |")
    lines.append(f"| **Total** | **{s_total}** | **{c_total}** | **{m_total}** | "
                 f"**{s_total-c_total:+d}** | **{s_total/m_total*100:.1f}%** |")
    lines.append("")
    lines.append(f"- Sources coded: **12**  ")
    lines.append(f"- Total coded mentions: **{m_total}** (strength {s_total}, concern {c_total})  ")
    lines.append(f"- Overall strength share: **{s_total/m_total*100:.1f}%**  ")
    lines.append(f"- Net-positive themes: **{pos}**; net-negative: **{neg}**  ")
    lines.append(f"- Most positive: **{sent[0][0]} ({sent[0][4]:+d})**; "
                 f"most negative: **{sent[-1][0]} ({sent[-1][4]:+d})**  ")
    lines.append(f"- Average mentions per source: **{m_total/12:.2f}**\n")

    os.makedirs(DOCS, exist_ok=True)
    with open(os.path.join(DOCS, "STATS.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("Wrote docs/STATS.md")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
